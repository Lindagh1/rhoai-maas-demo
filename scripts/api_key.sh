#!/usr/bin/env bash
# api_key.sh - Get-or-create the demo MaaS API key.
#
# Uses the MaaS management API (/maas-api/v1/api-keys) as documented in
# official RHOAI 3.5 docs section "Manage Models-as-a-Service by using the
# CLI and API". Authenticates the *management* call with the current OpenShift
# OIDC token (oc whoami -t) -- the management API accepts OIDC tokens or API
# keys. The resulting API key (prefix sk-oai-) is what's used for all
# *inference* calls afterwards, and is the only thing persisted, in
# .env.local (gitignored, never printed in full after creation).
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
source scripts/lib.sh

ENV_FILE=".env.local"

get_or_create_api_key() {
  if [[ -f "$ENV_FILE" ]] && grep -q '^MAAS_API_KEY=' "$ENV_FILE"; then
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    if [[ -n "${MAAS_API_KEY:-}" ]]; then
      echo "$MAAS_API_KEY"
      return 0
    fi
  fi

  local host resp key id
  host="$(maas_host_url)"
  resp=$(curl -sSk --connect-timeout 10 --max-time 30 \
    -H "Authorization: Bearer $(oc whoami -t)" \
    -H "Content-Type: application/json" \
    -X POST \
    -d '{"name":"rhoai-maas-demo-key","description":"rhoai-maas-demo happy-path key","expiresIn":"1h","subscription":"maas-demo-subscription"}' \
    "${host}/maas-api/v1/api-keys" 2>/dev/null || echo "{}")

  key=$(echo "$resp" | python3 -c "import json,sys; print(json.load(sys.stdin).get('key',''))" 2>/dev/null || echo "")
  id=$(echo "$resp" | python3 -c "import json,sys; print(json.load(sys.stdin).get('id',''))" 2>/dev/null || echo "")

  if [[ -z "$key" ]]; then
    err "Failed to create MaaS API key. Response: ${resp:0:300}" >&2
    return 1
  fi

  {
    echo "# Generated by scripts/api_key.sh — DO NOT COMMIT"
    echo "MAAS_API_KEY=$key"
    echo "MAAS_API_KEY_ID=$id"
    echo "MAAS_URL=$host"
  } > "$ENV_FILE"
  chmod 600 "$ENV_FILE"

  info "Created new MaaS API key (id: $id), stored in $ENV_FILE" >&2
  echo "$key"
}
